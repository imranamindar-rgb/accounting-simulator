function tierForChapter(chapter: number): 'starter' | 'accruals' | 'intermediate' | 'advanced' {
  if (chapter <= 3) return 'starter'
  if (chapter === 5) return 'accruals'
  if (chapter <= 9) return 'intermediate'
  return 'advanced'
}

